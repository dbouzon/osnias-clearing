// Package pilot implements the COORD Pilot local service (M-COORD-PILOT-02,
// MVP): a loopback-only HTTP service, token-authenticated per session, which
// orchestrates mission transitions EXCLUSIVELY through the normative engine
// (no duplication of the closed transition table), applies budget control
// before any adapter call (R3), intercepts the human stop at the service
// (R4, ARRET_PILOTE distinct from the engine's ECART), and performs every
// resume through the normative device (resume N-16/N-17). The PILOTE role is
// attached ONLY to the authenticated local session and is never derivable
// from a request body (S4). Errors are explicit, typed, journaled, never
// masked (conception §2.4).
