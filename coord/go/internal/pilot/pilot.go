// Acteur du pilotage local : rôle PILOTE attaché à la session authentifiée
// uniquement, jamais dérivable d'un corps de requête (S4).
const ActeurPiloteLocal = "pilote-local"

// Journal du service (authentifications refusées, etc.), distinct du journal
// par mission.
const nomJournalService = "journal-service.jsonl"

// Service: the COORD Pilot local service.
type Service struct {
	ref   *missions.Referentiel
	token string
	uiDir string
	mux   *http.ServeMux
}

// NouveauService validates the listen address (loopback only, S3) and the
// repository conformity (R2/S5: a malformed or empty habilitation
// configuration anywhere refuses the startup, fail closed), then builds the
// service. The token is generated by the caller (cmd) or by the tests; it is
// displayed on the console only, never journaled, never exposed.
func NouveauService(ref *missions.Referentiel, uiDir, token, adresse string) (*Service, error) {
	if strings.TrimSpace(token) == "" {
		return nil, errors.New("service : token d'authentification locale requis")
	}
	if err := verifieLoopback(adresse); err != nil {
		return nil, err
	}
	if ref == nil {
		return nil, errors.New("service : referentiel requis")
	}
	if err := ref.EstConforme(); err != nil {
		return nil, fmt.Errorf("demarrage refuse (N-05, fail closed) : %w", err)
	}
	if uiDir != "" {
		if _, err := os.Stat(filepath.Join(uiDir, "index.html")); err != nil {
			return nil, fmt.Errorf("demarrage refuse : UI absente de %s (fail closed)", uiDir)
		}
	}
	s := &Service{ref: ref, token: token, uiDir: uiDir}
	s.mux = http.NewServeMux()
	s.routes()
	return s, nil
}

// verifieLoopback refuses any non-loopback listen address (S3, fail closed).
func verifieLoopback(adresse string) error {
	host, _, err := net.SplitHostPort(adresse)
	if err != nil {
		host = adresse
	}
	if host == "" {
		return fmt.Errorf("ecoute refusee : adresse %q sans hote explicite (S3, fail closed)", adresse)
	}
	switch strings.ToLower(host) {
	case "127.0.0.1", "localhost", "::1":
		return nil
	}
	return fmt.Errorf("ecoute refusee : %s n'est pas une adresse loopback (S3, fail closed)", adresse)
}

// Handler returns the service HTTP handler with a body-size limit.
func (s *Service) Handler() http.Handler {
	return http.MaxBytesHandler(s.mux, 1<<20)
}

func (s *Service) routes() {
	s.mux.HandleFunc("GET /health", s.health)
	s.mux.Handle("GET /", http.FileServer(http.Dir(s.uiDir)))
	s.mux.HandleFunc("POST /api/mission", s.creerMission)
	s.mux.HandleFunc("GET /api/missions", s.listerMissions)
	s.mux.HandleFunc("GET /api/mission/{issue}", s.obtenirMission)
	s.mux.HandleFunc("POST /api/mission/{issue}/transition", s.transition)
	s.mux.HandleFunc("POST /api/mission/{issue}/arret", s.arretDemander)
	s.mux.HandleFunc("POST /api/mission/{issue}/arret/lever", s.arretLever)
	s.mux.HandleFunc("POST /api/mission/{issue}/reprise", s.reprise)
}

// ---- journalisation (délégation stricte à persist.JournalExecute, N-19) ----

type entreeJournal struct {
	Type   string `json:"type"`
	Trace  string `json:"trace,omitempty"`
	Issue  string `json:"issue,omitempty"`
	Detail string `json:"detail,omitempty"`
}

func (s *Service) trace() string {
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	return hex.EncodeToString(b)
}

func (s *Service) cheminJournal(issue string) string {
	return missions.JournalPath(s.ref.Racine(), issue)
}

// journalService journalise au niveau du service (auth, démarrage) : fichier
// distinct des journaux de mission. L'erreur n'est JAMAIS masquée (C5) :
// elle est tracée sur stderr ET retournée à l'appelant.
func (s *Service) journalService(e entreeJournal) error {
	if e.Trace == "" {
		e.Trace = s.trace()
	}
	if err := journalAjouter(filepath.Join(s.ref.Racine(), nomJournalService), e); err != nil {
		fmt.Fprintln(os.Stderr, "journal de service indisponible : "+err.Error())
		return err
	}
	return nil
}

// journalMission journalise dans le journal de la mission. L'erreur est
// retournée à l'appelant, jamais ignorée (C5) : toute écriture de journal
// manquante d'une opération est EXPLICITE (réponse typée ERREUR_JOURNAL).
// Ne prend AUCUN verrou : doit être appelée DANS une transaction (verrou
// de mission déjà détenu) ou hors opération d'écriture.
func (s *Service) journalMission(issue string, e entreeJournal) error {
	if e.Trace == "" {
		e.Trace = s.trace()
	}
	e.Issue = issue
	return journalAjouter(s.cheminJournal(issue), e)
}

func journalAjouter(chemin string, entree any) error {
	if err := os.MkdirAll(filepath.Dir(chemin), 0o755); err != nil {
		return err
	}
	// Forme canonique uniquement : le sérialiseur normatif n'accepte que
	// des valeurs décodées JSON (jamais de structs brutes).
	raw, err := json.Marshal(entree)
	if err != nil {
		return err
	}
	var m map[string]any
	if err := json.Unmarshal(raw, &m); err != nil {
		return err
	}
	_, err = persist.JournalExecute([]any{m}, chemin)
	return err
}

// ---- réponses ----

func reponseJSON(w http.ResponseWriter, code int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.Header().Set("X-Content-Type-Options", "nosniff")
	w.WriteHeader(code)
	_ = json.NewEncoder(w).Encode(v)
}

func (s *Service) refuser(w http.ResponseWriter, code int, typeErr, motif string) {
	reponseJSON(w, code, erreurAPI{Trace: s.trace(), Type: typeErr, Motif: motif})
}

type erreurAPI struct {
	Code  int    `json:"-"`
	Trace string `json:"trace"`
	Type  string `json:"type"`
	Motif string `json:"motif"`
}

// erreurService : refus typé (code HTTP + type + motif) qu'une transaction
// fait remonter AU gestionnaire de réponse ; l'état n'est PAS sauvegardé.
type erreurService struct {
	code  int
	typ   string
	motif string
}

func (e *erreurService) Error() string { return e.typ + " : " + e.motif }

// erreurJournal transforme un échec d'écriture de journal en refus typé
// ERREUR_JOURNAL, explicite et jamais masqué (C5).
func erreurJournal(contexte string, err error) *erreurService {
	return &erreurService{http.StatusInternalServerError, "ERREUR_JOURNAL",
		contexte + " : journal indisponible : " + err.Error()}
}

// repondreErreur expose l'erreur d'une transaction : refus typé, mission
// inconnue, ou défaut interne EXPLICITE (jamais masqué).
func (s *Service) repondreErreurTransaction(w http.ResponseWriter, err error) {
	var es *erreurService
	if errors.As(err, &es) {
		s.refuser(w, es.code, es.typ, es.motif)
		return
	}
	if errors.Is(err, missions.ErrIntrouvable) {
		s.refuser(w, http.StatusNotFound, "MISSION_INCONNUE", err.Error())
		return
	}
	s.refuser(w, http.StatusInternalServerError, "INTERNE", err.Error())
}

// auth verifie le token local (S1/S2). Returns 0 on success. Un refus
// d'authentification reste TOUJOURS un 401 (décision de sécurité prioritaire)
// mais une défaillance du journal de service est signalée dans le motif,
// jamais masquée (C5).
func (s *Service) auth(r *http.Request) (int, string) {
	t := r.Header.Get("X-Coord-Pilot-Token")
	if t == "" {
		err := s.journalService(entreeJournal{Type: "REFUS_AUTH", Detail: "token absent"})
		motif := "token d'authentification locale absent (401)"
		if err != nil {
			motif += " ; journal de service indisponible : " + err.Error()
		}
		return http.StatusUnauthorized, motif
	}
	if t != s.token {
		err := s.journalService(entreeJournal{Type: "REFUS_AUTH", Detail: "token invalide ou perime"})
		motif := "token d'authentification locale invalide ou perime (401)"
		if err != nil {
			motif += " ; journal de service indisponible : " + err.Error()
		}
		return http.StatusUnauthorized, motif
	}
	return 0, ""
}

